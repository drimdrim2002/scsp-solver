"""P2 gate: the native LP engine against HiGHS LP (black box) on every benchmark instance.

    python -I -m scsp.bench.lpcheck                      # all instances, resumes
    python -I -m scsp.bench.lpcheck --sets scp4 rail     # a subset
    python -I -m scsp.bench.lpcheck --report-only

Each instance runs in its own process, one at a time. Both solvers get the LP relaxation
(0 <= x <= 1) of the same Model, one thread, and are timed without model loading:
HiGHS by the wall time of run(), ours by the wall time of the call into the engine
(including the copy into its own matrix format).

Output: benchmarks/results/lp_check.jsonl (one line per instance), lp_check.csv, lp_check.md.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

from .catalog import bench_dir, discover

METHODS = ("auto", "dual", "sifting")
GATE = 1e-6


def highs_lp(model, presolve: bool = True, time_limit: float = 300.0) -> dict:
    import highspy

    a, lower, upper = model.to_scipy()
    a = a.tocsr()
    n = model.n_cols
    inf = highspy.kHighsInf
    lp = highspy.HighsLp()
    lp.num_col_ = n
    lp.num_row_ = a.shape[0]
    lp.col_cost_ = model.cost
    lp.col_lower_ = np.zeros(n)
    lp.col_upper_ = np.ones(n)
    lp.row_lower_ = np.where(np.isinf(lower), -inf, lower)
    lp.row_upper_ = np.where(np.isinf(upper), inf, upper)
    lp.offset_ = model.obj_offset
    lp.a_matrix_.format_ = highspy.MatrixFormat.kRowwise
    lp.a_matrix_.start_ = a.indptr
    lp.a_matrix_.index_ = a.indices
    lp.a_matrix_.value_ = a.data
    h = highspy.Highs()
    h.setOptionValue("output_flag", False)
    h.setOptionValue("threads", 1)
    h.setOptionValue("presolve", "on" if presolve else "off")
    h.setOptionValue("time_limit", float(time_limit))
    h.passModel(lp)
    t = time.perf_counter()
    h.run()
    t = time.perf_counter() - t
    info = h.getInfo()
    status = h.modelStatusToString(h.getModelStatus())
    return dict(status=status, obj=float(info.objective_function_value) if status == "Optimal" else None,
                time=t, iters=int(info.simplex_iteration_count), version=h.version())


def run_one(name: str, time_limit: float = 300.0) -> dict:
    from ..lp import solve_lp_arrays
    from .catalog import find

    inst = find(name)
    model = inst.load()
    a, lower, upper = model.to_scipy()
    n = model.n_cols
    rec = dict(instance=name, set=inst.set, rows=int(a.shape[0]), cols=int(n), nnz=int(a.nnz))
    rec["highs"] = highs_lp(model, True, time_limit)
    rec["highs_nopre"] = highs_lp(model, False, time_limit)
    zeros, ones = np.zeros(n), np.ones(n)
    for method in METHODS:
        t = time.perf_counter()
        r = solve_lp_arrays(model.cost, a, lower, upper, zeros, ones, offset=model.obj_offset, method=method,
                            time_limit=time_limit)
        t = time.perf_counter() - t
        rec[method] = dict(status=r.status, obj=r.obj, time=t, core_time=r.runtime, **r.stats)
    return rec


def rel_err(ours, ref):
    if ours is None or ref is None:
        return None
    return abs(ours - ref) / max(1.0, abs(ref))


def gmean(vals):
    vals = [v for v in vals if v is not None and v > 0]
    return math.exp(sum(math.log(v) for v in vals) / len(vals)) if vals else float("nan")


def report(records: list[dict], prefix: Path) -> dict:
    rows = []
    for r in records:
        h = r["highs"]
        row = dict(instance=r["instance"], set=r["set"], rows=r["rows"], cols=r["cols"], nnz=r["nnz"],
                   highs_status=h["status"], highs_obj=h["obj"], highs_time=h["time"], highs_iters=h["iters"],
                   highs_nopre_time=r["highs_nopre"]["time"])
        for mth in METHODS:
            o = r[mth]
            row[f"{mth}_status"] = o["status"]
            row[f"{mth}_obj"] = o["obj"]
            row[f"{mth}_relerr"] = rel_err(o["obj"], h["obj"])
            row[f"{mth}_time"] = o["time"]
            row[f"{mth}_iters"] = o["dual_iters"] + o["primal_iters"]
            row[f"{mth}_ratio"] = o["time"] / h["time"] if h["time"] > 0 else None
        row["auto_method"] = r["auto"]["method"]
        row["auto_work_cols"] = r["auto"]["work_cols"]
        row["auto_sift_rounds"] = r["auto"]["sift_rounds"]
        rows.append(row)
    with open(f"{prefix}.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    def ok(row, mth):
        e = row[f"{mth}_relerr"]
        return row[f"{mth}_status"] == "optimal" and e is not None and e <= GATE

    summary = dict(instances=len(rows))
    lines = ["# LP check: scsp LP engine vs HiGHS LP", "",
             "Generated by `python -m scsp.bench.lpcheck`. Relative error is `|ours - highs| / max(1, |highs|)`.",
             "Time ratio is ours / HiGHS (default settings, presolve on), one thread each, single run.", ""]
    lines += ["| method | optimal | rel. error <= 1e-6 | max rel. error | total time s | geo. mean ratio | faster than HiGHS |",
              "|---|---|---|---|---|---|---|"]
    for mth in METHODS:
        errs = [row[f"{mth}_relerr"] for row in rows if row[f"{mth}_relerr"] is not None]
        ratios = [row[f"{mth}_ratio"] for row in rows if row[f"{mth}_status"] == "optimal"]
        s = dict(optimal=sum(row[f"{mth}_status"] == "optimal" for row in rows), passed=sum(ok(row, mth) for row in rows),
                 max_relerr=max(errs) if errs else None, total_time=sum(row[f"{mth}_time"] for row in rows),
                 gmean_ratio=gmean(ratios), faster=sum(v < 1.0 for v in ratios if v is not None))
        summary[mth] = s
        lines.append(f"| {mth} | {s['optimal']} / {len(rows)} | {s['passed']} / {len(rows)} | {s['max_relerr']:.1e} | "
                     f"{s['total_time']:.2f} | {s['gmean_ratio']:.2f} | {s['faster']} / {len(rows)} |")
    summary["highs_total_time"] = sum(row["highs_time"] for row in rows)
    summary["highs_nopre_total_time"] = sum(row["highs_nopre_time"] for row in rows)
    lines += ["", f"HiGHS total time: {summary['highs_total_time']:.2f} s (presolve on), "
                  f"{summary['highs_nopre_total_time']:.2f} s (presolve off).", "",
              "| set | n | max rel. error (auto) | HiGHS s | auto s | dual s | sifting s | auto ratio (geo. mean) | auto ratio max |",
              "|---|---|---|---|---|---|---|---|---|"]
    sets = []
    for row in rows:
        if row["set"] not in sets:
            sets.append(row["set"])
    for st in sets:
        rs = [row for row in rows if row["set"] == st]
        errs = [row["auto_relerr"] for row in rs if row["auto_relerr"] is not None]
        ratios = [row["auto_ratio"] for row in rs if row["auto_ratio"] is not None]
        lines.append(f"| {st} | {len(rs)} | {max(errs) if errs else float('nan'):.1e} | {sum(r['highs_time'] for r in rs):.3f} | "
                     f"{sum(r['auto_time'] for r in rs):.3f} | {sum(r['dual_time'] for r in rs):.3f} | "
                     f"{sum(r['sifting_time'] for r in rs):.3f} | {gmean(ratios):.2f} | {max(ratios) if ratios else float('nan'):.2f} |")
    slow = sorted(rows, key=lambda row: -(row["auto_ratio"] or 0))[:10]
    lines += ["", "Ten largest time ratios (auto):", "", "| instance | rows x cols | HiGHS s | auto s | ratio | method |",
              "|---|---|---|---|---|---|"]
    for row in slow:
        lines.append(f"| {row['instance']} | {row['rows']} x {row['cols']} | {row['highs_time']:.4f} | "
                     f"{row['auto_time']:.4f} | {row['auto_ratio']:.2f} | {row['auto_method']} |")
    Path(f"{prefix}.md").write_text("\n".join(lines) + "\n")
    return summary


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--one", help="run a single instance and print one JSON line (used internally)")
    ap.add_argument("--instances", nargs="*")
    ap.add_argument("--sets", nargs="*")
    ap.add_argument("--time-limit", type=float, default=300.0)
    ap.add_argument("--timeout", type=float, default=2400.0, help="seconds per instance process")
    ap.add_argument("--out", default=None, help="output prefix (default benchmarks/results/lp_check)")
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args(argv)
    if args.one:
        print(json.dumps(run_one(args.one, args.time_limit)))
        return 0
    prefix = Path(args.out) if args.out else bench_dir() / "results" / "lp_check"
    jsonl = Path(f"{prefix}.jsonl")
    done = {}
    if jsonl.exists():
        for line in jsonl.read_text().splitlines():
            rec = json.loads(line)
            done[rec["instance"]] = rec
    insts = discover()
    if args.instances:
        insts = [i for i in insts if i.name in set(args.instances)]
    if args.sets:
        insts = [i for i in insts if i.set in set(args.sets)]
    t0 = time.time()
    failed = []
    if not args.report_only:
        for inst in insts:
            if inst.name in done:
                continue
            cmd = [sys.executable, "-I", "-m", "scsp.bench.lpcheck", "--one", inst.name, "--time-limit",
                   str(args.time_limit)]
            try:
                out = subprocess.run(cmd, capture_output=True, text=True, timeout=args.timeout, cwd="/")
                rec = json.loads(out.stdout.strip().splitlines()[-1])
            except Exception as exc:  # timeout, crash or unreadable output
                failed.append(inst.name)
                print(f"[{time.time() - t0:7.0f}s] {inst.name:28s} FAILED: {type(exc).__name__}", flush=True)
                continue
            done[inst.name] = rec
            with open(jsonl, "a") as f:
                f.write(json.dumps(rec) + "\n")
            e = rel_err(rec["auto"]["obj"], rec["highs"]["obj"])
            print(f"[{time.time() - t0:7.0f}s] {inst.name:28s} highs {rec['highs']['time']:8.3f}s  auto "
                  f"{rec['auto']['time']:8.3f}s ({rec['auto']['method']})  dual {rec['dual']['time']:8.3f}s  sifting "
                  f"{rec['sifting']['time']:8.3f}s  relerr {e if e is None else format(e, '.1e')}", flush=True)
    records = [done[i.name] for i in insts if i.name in done]
    if records:
        s = report(records, prefix)
        print(json.dumps(s, indent=1))
    if failed:
        print("failed:", " ".join(failed))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
